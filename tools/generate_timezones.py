#!/usr/bin/env python3
"""Generate firmware clock offsets from the host's IANA tzdata."""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
from zoneinfo import ZoneInfo, available_timezones, reset_tzpath

# Cover all synchronized times accepted by the firmware through the ESP32
# Arduino core's signed 32-bit time_t limit.
START = 1700000000
END = 2147483647
STEP = 86400


def state_at(zone, timestamp):
    local = datetime.fromtimestamp(timestamp, timezone.utc).astimezone(zone)
    return int(local.utcoffset().total_seconds()), local.tzname()


def transitions(zone):
    previous = state_at(zone, START)
    entries = [(0, *previous)]
    earlier = START
    while earlier < END:
        later = min(earlier + STEP, END)
        current = state_at(zone, later)
        if current != previous:
            lo, hi = earlier + 1, later
            while lo < hi:
                midpoint = (lo + hi) // 2
                if state_at(zone, midpoint) == previous:
                    lo = midpoint + 1
                else:
                    hi = midpoint
            entries.append((lo, *current))
        previous, earlier = current, later
    return tuple(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tzdata', type=Path, default=Path('/usr/share/zoneinfo'))
    args = parser.parse_args()
    reset_tzpath([str(args.tzdata.resolve())])
    version = (args.tzdata / 'tzdata.zi').read_text().splitlines()[0].removeprefix('# version ')
    distinct = {}
    names = {}
    for name in sorted(available_timezones()):
        series = transitions(ZoneInfo(name))
        if series not in distinct:
            distinct[series] = len(distinct)
        names[name] = distinct[series]

    lines = [f'// IANA tzdata {version}, generated by tools/generate_timezones.py.',
             '// IANA timezone data is public domain.', 'constexpr ClockTransition clockTransitions[] = {']
    ranges = []
    offset = 0
    for series in distinct:
        ranges.append((offset, len(series)))
        for utc, delta, abbreviation in series:
            lines.append(f'    {{{utc}, {delta}, {json.dumps(abbreviation)}}},')
        offset += len(series)
    lines.extend(['};', 'constexpr ClockZone clockZones[] = {'])
    for name, index in names.items():
        first, count = ranges[index]
        lines.append(f'    {{{json.dumps(name)}, {first}, {count}}},')
    lines.extend(['};', ''])
    output = Path(__file__).resolve().parents[1] / 'include' / 'clock_timezones.inc'
    output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
